const ANDROID_DPI = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const HICOLOR = [16, 22, 24, 32, 48, 64, 128, 256, 512];

/** Map of absolute path → Buffer|string for everything this script owns. */
export async function buildAll() {
  const m = await loadMasters();
  const out = new Map();
  const put = (p, data) => out.set(p, data);
  const E = (...p) => path.join(EXPORT, ...p);

  const rounded = iconRounded(m);
  const small = iconSmall(m);
  const pick = (s) => (s <= 32 ? small : rounded);

  // Vector masters for consumers that take SVG.
  put(E('svg', 'app-icon.svg'), rounded);
  put(E('svg', 'app-icon-small.svg'), small);
  put(E('svg', 'app-icon-full-bleed.svg'), iconFullBleed(m));
  put(E('svg', 'lockup-dark.svg'), lockup(m));
  put(E('svg', 'lockup-light.svg'), lockup(m, true));
  put(E('svg', 'tv-banner.svg'), tvBanner(m));

  // Android (res/ mirrors app/src/main/res).
  for (const [dpi, k] of Object.entries(ANDROID_DPI)) {
    const res = (n) => E('android', 'res', `mipmap-${dpi}`, n);
    put(res('ic_launcher.png'), png(rounded, 48 * k));
    put(res('ic_launcher_round.png'), png(iconRound(m), 48 * k));
    put(res('ic_launcher_foreground.png'), png(adaptiveForeground(m), ADAPTIVE * k));
    put(res('ic_launcher_background.png'), png(adaptiveBackground(), ADAPTIVE * k));
    put(res('ic_launcher_monochrome.png'), png(adaptiveMonochrome(m), ADAPTIVE * k));
  }
  put(E('android', 'res', 'mipmap-anydpi-v26', 'ic_launcher.xml'), adaptiveXml(false));
  put(E('android', 'res', 'mipmap-anydpi-v26', 'ic_launcher_round.xml'), adaptiveXml(true));
  put(E('android', 'res', 'drawable-xhdpi', 'tv_banner.png'), png(tvBanner(m), 320, 180));
  put(E('android', 'play-store-512.png'), png(iconFullBleed(m), 512));

  // Linux (freedesktop hicolor theme + .desktop).
  for (const s of HICOLOR) put(E('linux', 'icons', 'hicolor', `${s}x${s}`, 'apps', `${APP_ID}.png`), png(pick(s), s));
  put(E('linux', 'icons', 'hicolor', 'scalable', 'apps', `${APP_ID}.svg`), rounded);
  put(E('linux', 'icons', 'hicolor', 'symbolic', 'apps', `${APP_ID}-symbolic.svg`), symbolic(m));
  put(E('linux', `${APP_ID}.desktop`), desktopEntry);

  // Windows (exe/installer icon; MSIX logos are a later packaging task).
  put(E('windows', 'app.ico'), ico([16, 24, 32, 48, 64, 256].map((s) => ({ size: s, data: png(pick(s), s) }))));

  // Web: site, server and NAS admin.
  put(E('web', 'favicon.svg'), small);
  put(E('web', 'favicon.ico'), ico([16, 32, 48].map((s) => ({ size: s, data: png(small, s) }))));
  put(E('web', 'icon-192.png'), png(rounded, 192));
  put(E('web', 'icon-512.png'), png(rounded, 512));
  put(E('web', 'apple-touch-icon.png'), png(iconFullBleed(m), 180));

  // Lockups for README, site and About.
  put(E('logo', 'lockup-dark.png'), png(lockup(m), 1024));
  put(E('logo', 'lockup-light.png'), png(lockup(m, true), 1024));

  // Placeholders.
  const ph = { poster: [400, 600], backdrop: [1280, 720], album: [512, 512], artist: [512, 512] };
  for (const [name, [w, h]] of Object.entries(ph)) {
    const svg = await readFile(path.join(PLACEHOLDERS, `${name}.svg`), 'utf8');
    put(path.join(PH_EXPORT, `${name}.png`), png(svg, w, h));
  }

  // One sheet to eyeball everything (PR reviews, README).
  put(path.join(BRAND, 'preview.png'), png(previewSheet(m, out), 1200));
  return out;
}

function previewSheet(m, out) {
  const img = (p, x, y, w, h) => {
    const b = out.get(p);
    return `<image x="${x}" y="${y}" width="${w}" height="${h}" href="data:image/png;base64,${b.toString('base64')}"/>`;
  };
  const E = (...p) => path.join(EXPORT, ...p);
  const hi = (s) => E('linux', 'icons', 'hicolor', `${s}x${s}`, 'apps', `${APP_ID}.png`);
  let body = `<rect width="1200" height="820" fill="#0b0b0f"/><rect y="410" width="1200" height="410" fill="${COLORS.paper}"/>`;
  for (const [y0] of [[20], [430]]) {
    let x = 30;
    for (const s of [16, 24, 32, 48, 64, 128, 256]) {
      body += img(hi(s), x, y0 + (256 - s) / 2, s, s);
      x += s + 24;
    }
    body += img(E('android', 'res', 'drawable-xhdpi', 'tv_banner.png'), x, y0 + 38, 320, 180);
  }
  body += img(E('logo', 'lockup-dark.png'), 30, 300, 0.4 * 1024, (0.4 * 1024 * 256) / 1060);
  body += img(E('logo', 'lockup-light.png'), 30, 710, 0.4 * 1024, (0.4 * 1024 * 256) / 1060);
  body += img(path.join(PH_EXPORT, 'poster.png'), 520, 290, 80, 120);
  body += img(path.join(PH_EXPORT, 'backdrop.png'), 620, 290, 213, 120);
  body += img(path.join(PH_EXPORT, 'album.png'), 853, 290, 120, 120);
  body += `<clipPath id="c"><circle cx="1053" cy="350" r="60"/></clipPath>`;
  body += `<g clip-path="url(#c)">${img(path.join(PH_EXPORT, 'artist.png'), 993, 290, 120, 120)}</g>`;
  // Android adaptive preview: foreground over background in circle and squircle masks.
  const fg = E('android', 'res', 'mipmap-xxxhdpi', 'ic_launcher_foreground.png');
  const bg = E('android', 'res', 'mipmap-xxxhdpi', 'ic_launcher_background.png');
  const mono = E('android', 'res', 'mipmap-xxxhdpi', 'ic_launcher_monochrome.png');
  body += `<clipPath id="a1"><circle cx="560" cy="650" r="66"/></clipPath><g clip-path="url(#a1)">${img(bg, 461, 551, 198, 198)}${img(fg, 461, 551, 198, 198)}</g>`;
  body += `<clipPath id="a2"><rect x="660" y="584" width="132" height="132" rx="34"/></clipPath><g clip-path="url(#a2)">${img(bg, 627, 551, 198, 198)}${img(fg, 627, 551, 198, 198)}</g>`;
  body += `<circle cx="890" cy="650" r="66" fill="#dfe7ea"/><g opacity="1">${img(mono, 791, 551, 198, 198).replace('<image', '<image style="filter:none"')}</g>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 820" width="1200" height="820">${body}</svg>`;
}

// ---------------------------------------------------------------- consistency with tokens

async function checkTokens() {
  const prim = JSON.parse(await readFile(path.join(DESIGN, 'tokens', 'primitive.tokens.json'), 'utf8'));
  const lune = prim.color.lune;
  const errs = [];
  if (lune['400'].$value.hex.toLowerCase() !== COLORS.accent) errs.push(`COLORS.accent ${COLORS.accent} != color.lune.400 ${lune['400'].$value.hex}`);
  if (lune['600'].$value.hex.toLowerCase() !== COLORS.accentOnLight) errs.push(`COLORS.accentOnLight ${COLORS.accentOnLight} != color.lune.600 ${lune['600'].$value.hex}`);
  const mark = await readFile(path.join(BRAND, 'src', 'mark.svg'), 'utf8');
  if (!mark.includes(`fill="${COLORS.accent}"`) || !mark.includes(`fill="${COLORS.moon}"`)) errs.push('brand/src/mark.svg colours differ from COLORS');
  return errs;
}

// ---------------------------------------------------------------- main

async function listFiles(dir) {
  const res = [];
  for (const e of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) res.push(...(await listFiles(p)));
    else res.push(p);
  }
  return res;
}

async function main() {
  const check = process.argv.includes('--check');
  const errs = await checkTokens();
  const out = await buildAll();
  const rel = (p) => path.relative(DESIGN, p);
  const owned = [...(await listFiles(EXPORT)), ...(await listFiles(PH_EXPORT))];
  if (check) {
    for (const [p, data] of out) {
      const cur = await readFile(p).catch(() => null);
      if (!cur || !cur.equals(Buffer.from(data))) errs.push(`stale: ${rel(p)}`);
    }
    for (const p of owned) if (!out.has(p)) errs.push(`orphan: ${rel(p)}`);
    if (errs.length) {
      console.error(`brand:check FAILED (run \`just design brand\`):\n  ${errs.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`brand:check OK: ${out.size} files up to date`);
    return;
  }
  if (errs.length) {
    console.error(errs.join('\n'));
    process.exit(1);
  }
  for (const p of owned) if (!out.has(p)) await rm(p);
  let bytes = 0;
  for (const [p, data] of out) {
    await mkdir(path.dirname(p), { recursive: true });
    await writeFile(p, data);
    bytes += Buffer.byteLength(data);
  }
  console.log(`brand: wrote ${out.size} files, ${(bytes / 1024).toFixed(0)} KiB`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
