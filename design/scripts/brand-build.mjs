// ---------------------------------------------------------------- masters

function attr(el, name) {
  const m = el.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? m[1] : undefined;
}

function element(svg, id) {
  const m = svg.match(new RegExp(`<path[^>]*\\sid="${id}"[^>]*/>`));
  if (!m) throw new Error(`no <path id="${id}">`);
  return m[0];
}

export async function loadMasters() {
  const mark = await readFile(path.join(BRAND, 'src', 'mark.svg'), 'utf8');
  const word = await readFile(path.join(BRAND, 'src', 'wordmark.svg'), 'utf8');
  const moon = element(mark, 'moon');
  const play = element(mark, 'play');
  const wm = element(word, 'wordmark');
  const vb = attr(word.match(/<svg[^>]*>/)[0], 'viewBox').split(/\s+/).map(Number);
  return {
    moonD: attr(moon, 'd'),
    playD: attr(play, 'd'),
    playStroke: Number(attr(play, 'stroke-width')),
    wordD: attr(wm, 'd'),
    wordBox: { x: vb[0], y: vb[1], w: vb[2], h: vb[3] },
  };
}

// ---------------------------------------------------------------- composition helpers

const f = (n) => +n.toFixed(3);

/** Mark (1024 grid) scaled to `size` and centred at (cx, cy). */
function mark(m, cx, cy, size, { moon = COLORS.moon, play = COLORS.accent } = {}) {
  const s = size / 1024;
  return `<g transform="translate(${f(cx - size / 2)} ${f(cy - size / 2)}) scale(${f(s)})">
  <path fill="${moon}" d="${m.moonD}"/>
  <path fill="${play}" stroke="${play}" stroke-width="${m.playStroke}" stroke-linejoin="round" d="${m.playD}"/>
</g>`;
}

/** Wordmark scaled to cap-box height `h`, left edge at x, vertically centred at cy. */
function wordmark(m, x, cy, h, fill = COLORS.moon) {
  const s = h / m.wordBox.h;
  const tx = x - m.wordBox.x * s;
  const ty = cy - (m.wordBox.y + m.wordBox.h / 2) * s;
  return { svg: `<path transform="translate(${f(tx)} ${f(ty)}) scale(${f(s)})" fill="${fill}" d="${m.wordD}"/>`, width: m.wordBox.w * s };
}

const night = (id = 'night') =>
  `<linearGradient id="${id}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${COLORS.nightTop}"/><stop offset="1" stop-color="${COLORS.nightBottom}"/></linearGradient>`;

const doc = (w, h, body, defs = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">\n${HEADER}\n${defs ? `<defs>${defs}</defs>\n` : ''}${body}\n</svg>\n`;

// ---------------------------------------------------------------- icon shapes (1024 canvas)

/** Rounded-square app icon with margin: Linux hicolor, Windows, legacy Android, web. */
export const iconRounded = (m) =>
  doc(1024, 1024, `<rect x="64" y="64" width="896" height="896" rx="200" fill="url(#night)"/>\n${mark(m, 512, 512, 760)}`, night());

/** Tighter variant for 16–32 px: bigger mark, smaller margin (favicon, small hicolor sizes). */
export const iconSmall = (m) =>
  doc(1024, 1024, `<rect x="0" y="0" width="1024" height="1024" rx="200" fill="url(#night)"/>\n${mark(m, 512, 512, 1000)}`, night());

/** Full-bleed square: Play Store 512 (Google applies its own mask). */
export const iconFullBleed = (m) => doc(1024, 1024, `<rect width="1024" height="1024" fill="url(#night)"/>\n${mark(m, 512, 512, 700)}`, night());

/** Legacy round launcher icon (Android < 8). */
export const iconRound = (m) => doc(1024, 1024, `<circle cx="512" cy="512" r="448" fill="url(#night)"/>\n${mark(m, 512, 512, 740)}`, night());

// Android adaptive icon layers: 108 dp canvas, the launcher mask shows the central 72 dp;
// keep the mark inside the 66 dp safe circle.
const ADAPTIVE = 108;
export const adaptiveForeground = (m) => doc(ADAPTIVE, ADAPTIVE, mark(m, 54, 54, 62));
export const adaptiveBackground = () => doc(ADAPTIVE, ADAPTIVE, `<rect width="${ADAPTIVE}" height="${ADAPTIVE}" fill="url(#night)"/>`, night());
export const adaptiveMonochrome = (m) => doc(ADAPTIVE, ADAPTIVE, mark(m, 54, 54, 62, { moon: '#ffffff', play: '#ffffff' }));

/** Android TV launcher banner 320×180 (xhdpi): mark + name on the night gradient. */
export function tvBanner(m) {
  const markSize = 104;
  const gap = 14;
  const wordH = 36;
  const ww = wordmark(m, 0, 0, wordH).width;
  const total = markSize * 0.66 + gap + ww; // visible mark width ≈ 0.66 of its box
  const x0 = (320 - total) / 2 - markSize * 0.15;
  const w = wordmark(m, x0 + markSize * 0.81 + gap, 90, wordH);
  return doc(320, 180, `<rect width="320" height="180" fill="url(#night)"/>\n${mark(m, x0 + markSize / 2, 90, markSize)}\n${w.svg}`, night());
}

/** Horizontal lockup: mark + wordmark. `light` = for light backgrounds. */
export function lockup(m, light = false) {
  const H = 256;
  const markSize = 256;
  const wordH = 104;
  const c = light ? { moon: COLORS.nightTop, play: COLORS.accentOnLight, word: COLORS.ink } : { moon: COLORS.moon, play: COLORS.accent, word: COLORS.moon };
  const wx = markSize * 0.81 + 36;
  const w = wordmark(m, wx, H / 2, wordH, c.word);
  const W = Math.ceil(wx + w.width + 8);
  return doc(W, H, `${mark(m, markSize / 2, H / 2, markSize, c)}\n${w.svg}`);
}

/** GNOME/KDE symbolic icon: single colour, 16 px grid; the desktop recolours it. */
export const symbolic = (m) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="16" height="16">\n${HEADER}\n${mark(m, 512, 512, 1080, { moon: '#2e3436', play: '#2e3436' })}\n</svg>\n`;

// ---------------------------------------------------------------- raster + containers

export function png(svg, width, height) {
  const r = new Resvg(svg, { fitTo: { mode: 'width', value: width }, font: { loadSystemFonts: false } });
  const img = r.render();
  if (height && img.height !== height) throw new Error(`expected ${width}×${height}, got ${img.width}×${img.height}`);
  return Buffer.from(img.asPng());
}

/** ICO with PNG-compressed images (Vista+, all browsers). */
export function ico(images) {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(0, 0);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size >= 256 ? 0 : size, e);
    head.writeUInt8(size >= 256 ? 0 : size, e + 1);
    head.writeUInt8(0, e + 2);
    head.writeUInt8(0, e + 3);
    head.writeUInt16LE(1, e + 4);
    head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(data.length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([head, ...images.map((i) => i.data)]);
}

