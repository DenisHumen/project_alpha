// CSS emitter (server web admin, NAS admin, site): custom properties `--pa-<path>`.
// Dark theme and desktop density are the defaults on :root; switch with
// `data-theme="light"` and `data-density="tv|tablet|phone"` on any element.
// Typography gives a `font` shorthand plus `-letter-spacing` and `-font-feature-settings`.

import { checkNames, fmt, fontFeatures, rgba8, toMs, toPx } from './tokens-model.mjs';

export const DEFAULT_DENSITY = 'desktop';
const GENERIC = new Set(['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui', 'ui-serif', 'ui-sans-serif', 'ui-monospace', 'ui-rounded', 'emoji', 'math', 'fangsong']);

const varName = (p) => `--pa-${p.replace(/\./g, '-')}`;
const color = (c) => `#${rgba8(c).filter((x, i) => i < 3 || x !== 255).map((x) => x.toString(16).padStart(2, '0')).join('')}`;
const dim = (d) => (d.unit === 'rem' ? `${fmt(d.value)}rem` : `${fmt(toPx(d))}px`);
const ms = (d) => `${toMs(d)}ms`;
const bezier = (v) => `cubic-bezier(${v.map(fmt).join(', ')})`;
const families = (v) => (Array.isArray(v) ? v : [v]).map((s) => (GENERIC.has(s) ? s : JSON.stringify(s))).join(', ');
const weight = (w) => String(w);

/** Returns [[suffix, value], …] for one token; suffix '' is the token itself. */
function decls(type, v, ext) {
  switch (type) {
    case 'color': return [['', color(v)]];
    case 'dimension': return [['', dim(v)]];
    case 'number': return [['', fmt(v)]];
    case 'duration': return [['', ms(v)]];
    case 'cubicBezier': return [['', bezier(v)]];
    case 'fontWeight': return [['', weight(v)]];
    case 'fontFamily': return [['', families(v)]];
    case 'shadow':
      return [['', (Array.isArray(v) ? v : [v]).map((s) => `${dim(s.offsetX)} ${dim(s.offsetY)} ${dim(s.blur)} ${dim(s.spread ?? { value: 0, unit: 'px' })} ${color(s.color)}`).join(', ')]];
    case 'gradient':
      // Position 0 is the edge that carries text (bottom of a backdrop).
      return [['', `linear-gradient(to top, ${v.map((s) => `${color(s.color)} ${fmt(s.position * 100)}%`).join(', ')})`]];
    case 'transition':
      return [['', `${ms(v.duration)} ${bezier(v.timingFunction)} ${ms(v.delay)}`]];
    case 'typography': {
      const feats = fontFeatures(ext);
      return [
        ['', `${weight(v.fontWeight)} ${dim(v.fontSize)}/${fmt(v.lineHeight)} ${families(v.fontFamily)}`],
        ['-letter-spacing', dim(v.letterSpacing)],
        ['-font-feature-settings', feats.length ? feats.map((x) => `"${x}"`).join(', ') : 'normal'],
      ];
    }
    default:
      throw new Error(`no CSS mapping for $type ${type}`);
  }
}

const lines = (e, v, ext) => decls(e.type, v, ext).map(([s, x]) => `  ${varName(e.p)}${s}: ${x};`);

/** @param {import('./tokens-model.mjs').TokenModel} model */
export function emitCss(model) {
  const all = [...model.constant, ...model.byTheme, ...model.byDensity];
  const names = all.flatMap((e) => decls(e.type, e.value ?? Object.values(e.values)[0], e.ext ?? Object.values(e.exts ?? {})[0]).map(([s]) => [e.p, varName(e.p) + s]));
  checkNames(names, new Set(), 'CSS custom property');

  const dd = model.densities.includes(DEFAULT_DENSITY) ? DEFAULT_DENSITY : model.densities[0];
  const [defTheme, ...otherThemes] = model.themes;
  const theme = (t) => model.byTheme.flatMap((e) => lines(e, e.values[t], e.ext));
  const density = (d) => model.byDensity.flatMap((e) => lines(e, e.values[d], e.exts[d]));
  const block = (sel, body) => `${sel} {\n${body.join('\n')}\n}\n`;

  const out = [
    `/* SPDX-License-Identifier: MPL-2.0 */
/* GENERATED by design/scripts/tokens-build.mjs from design/tokens (W3C DTCG). Do not edit;
   change the JSON and run \`just design tokens\`.
   Defaults: ${defTheme} theme, ${dd} density. Override with data-theme / data-density on any element. */
`,
    block(':root', model.constant.flatMap((e) => lines(e, e.value, e.ext))),
    block(`:root,\n[data-theme="${defTheme}"]`, [`  color-scheme: ${defTheme};`, ...theme(defTheme)]),
    ...otherThemes.map((t) => block(`[data-theme="${t}"]`, [`  color-scheme: ${t};`, ...theme(t)])),
    block(`:root,\n[data-density="${dd}"]`, density(dd)),
    ...model.densities.filter((d) => d !== dd).map((d) => block(`[data-density="${d}"]`, density(d))),
  ];
  return out.join('\n');
}
