// Dart emitter (Flutter package pa_design): PaTokens, PaColorScheme.dark|light,
// PaDensity.tv|desktop|tablet|phone. The API predates DSN-003 and must stay stable.

import { camelName, checkNames, firstFamily, fontFeatures, toMs, toPx } from './tokens-model.mjs';

const PACKAGE = 'pa_design';

const dbl = (n) => {
  const s = String(Math.round(n * 10000) / 10000);
  return s.includes('.') || s.includes('e') ? s : `${s}.0`;
};
const color = (c) => {
  const a = Math.round((c.alpha ?? 1) * 255);
  const [r, g, b] = c.components.map((x) => Math.round(x * 255));
  return `Color(0x${[a, r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase()})`;
};
const ms = (d) => `Duration(milliseconds: ${toMs(d)})`;
const px = (d) => dbl(toPx(d));
const weight = (w) => `FontWeight.w${Math.round(w / 100) * 100}`;

const TYPE = {
  color: 'Color', dimension: 'double', number: 'double', duration: 'Duration', cubicBezier: 'Cubic',
  shadow: 'BoxShadow', gradient: 'LinearGradient', transition: 'PaTransition', typography: 'TextStyle',
  fontWeight: 'FontWeight', fontFamily: 'String',
};

function value(type, v, ext) {
  switch (type) {
    case 'color': return color(v);
    case 'dimension': return px(v);
    case 'number': return dbl(v);
    case 'duration': return ms(v);
    case 'cubicBezier': return `Cubic(${v.map(dbl).join(', ')})`;
    case 'fontWeight': return weight(v);
    case 'fontFamily': return `'${firstFamily(v)}'`;
    case 'shadow': {
      const s = Array.isArray(v) ? v[0] : v;
      return `BoxShadow(color: ${color(s.color)}, offset: Offset(${px(s.offsetX)}, ${px(s.offsetY)}), blurRadius: ${px(s.blur)}, spreadRadius: ${px(s.spread ?? { value: 0, unit: 'px' })})`;
    }
    case 'gradient':
      // Position 0 is the edge that carries text (bottom of a backdrop).
      return `LinearGradient(begin: Alignment.bottomCenter, end: Alignment.topCenter, colors: [${v.map((s) => color(s.color)).join(', ')}], stops: [${v.map((s) => dbl(s.position)).join(', ')}])`;
    case 'transition':
      return `PaTransition(duration: ${ms(v.duration)}, delay: ${ms(v.delay)}, curve: Cubic(${v.timingFunction.map(dbl).join(', ')}))`;
    case 'typography': {
      const size = toPx(v.fontSize);
      const feats = fontFeatures(ext);
      const ff = feats.length ? `, fontFeatures: [${feats.map((f) => (f === 'tnum' ? 'FontFeature.tabularFigures()' : `FontFeature('${f}')`)).join(', ')}]` : '';
      // Inter has an optical-size axis 14–32: follow the font size.
      const opsz = Math.min(32, Math.max(14, size));
      return `TextStyle(fontFamily: '${firstFamily(v.fontFamily)}', package: '${PACKAGE}', fontSize: ${dbl(size)}, fontWeight: ${weight(v.fontWeight)}, letterSpacing: ${px(v.letterSpacing)}, height: ${dbl(v.lineHeight)}${ff}, fontVariations: [FontVariation('opsz', ${dbl(opsz)})])`;
    }
    default:
      throw new Error(`no Dart mapping for $type ${type}`);
  }
}

/** @param {import('./tokens-model.mjs').TokenModel} model */
export function emitDart(model) {
  const all = [...model.constant, ...model.byTheme, ...model.byDensity];
  for (const e of all) if (!TYPE[e.type]) throw new Error(`${e.p}: unsupported type ${e.type}`);
  checkNames(all.map((e) => [e.p, camelName(e.p)]), new Set(), 'Dart name');

  const cls = (className, doc, list, variants, extOf) => {
    const fields = list.map((e) => `  /// \`${e.p}\`\n  final ${TYPE[e.type]} ${camelName(e.p)};`).join('\n');
    const ctor = `  const ${className}._({\n${list.map((e) => `    required this.${camelName(e.p)},`).join('\n')}\n  });`;
    const consts = variants
      .map((v) => `  static const ${v} = ${className}._(\n${list.map((e) => `    ${camelName(e.p)}: ${value(e.type, e.values[v], extOf(e, v))},`).join('\n')}\n  );`)
      .join('\n\n');
    return `/// ${doc}\nfinal class ${className} {\n${ctor}\n\n${consts}\n\n  static const values = <String, ${className}>{${variants.map((v) => `'${v}': ${v}`).join(', ')}};\n\n${fields}\n}\n`;
  };

  return `// SPDX-License-Identifier: MPL-2.0
// GENERATED by design/scripts/tokens-build.mjs from design/tokens (W3C DTCG). Do not edit;
// change the JSON and run \`just design tokens\`.

// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars

import 'package:flutter/widgets.dart';

/// Transition token (DTCG \`transition\`).
final class PaTransition {
  const PaTransition({required this.duration, required this.delay, required this.curve});
  final Duration duration;
  final Duration delay;
  final Curve curve;
}

/// Theme-independent, density-independent tokens.
abstract final class PaTokens {
${model.constant.map((e) => `  /// \`${e.p}\`\n  static const ${TYPE[e.type]} ${camelName(e.p)} = ${value(e.type, e.value, e.ext)};`).join('\n')}
}

${cls('PaColorScheme', 'Tokens that depend on the colour theme. Dark is the default (01 §4.1); TV is always dark.', model.byTheme, model.themes, (e) => e.ext)}
${cls('PaDensity', 'Tokens that depend on the density profile: tv (10-foot UI, 1920×1080 logical px), desktop, tablet, phone.', model.byDensity, model.densities, (e, d) => e.exts[d])}`;
}
