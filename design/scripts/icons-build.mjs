// Generates platform icon code from icons/svg/*.svg (DSN-004):
//   - Flutter: design/flutter/pa_design/lib/src/icons.g.dart (enum PaIcon, SVG data)
//   - Apple:   design/icons/generated/apple/PaIcons.xcassets (vector, template) + PaIcon.swift
// `--check` regenerates in memory and fails if anything on disk is stale (for CI).

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { DESIGN_DIR, REPO_DIR, camelCase, loadManifest } from './lib/icons.mjs';

const SVG_DIR = path.join(DESIGN_DIR, 'icons', 'svg');
const DART_FILE = path.join(DESIGN_DIR, 'flutter', 'pa_design', 'lib', 'src', 'icons.g.dart');
const APPLE_DIR = path.join(DESIGN_DIR, 'icons', 'generated', 'apple');
const HEADER = 'GENERATED by design/scripts/icons-build.mjs from design/icons/svg. Do not edit; run `just design icons`.';

const stripComment = (svg) => svg.replace(/^<!--.*?-->\n/, '').trim();

export function dart(icons) {
  const cases = icons
    .map(({ name, svg }) => `  ${camelCase(name)}('${name}', r'''${stripComment(svg)}'''),`)
    .join('\n')
    .replace(/,$/, ';');
  return `// SPDX-License-Identifier: MPL-2.0 AND ISC AND MIT
// ${HEADER}
// Icon geometry: Lucide (ISC; Feather-derived icons also MIT), see design/icons/LICENSE-lucide.txt.

/// UI icon set (Lucide-based, DSN-004). Every value is a 24×24 stroke SVG that
/// paints with \`currentColor\`. Render with \`PaIconView(PaIcon.play)\`.
enum PaIcon {
${cases}

  const PaIcon(this.id, this.svg);

  /// Stable kebab-case id (file name in design/icons/svg).
  final String id;

  /// Optimised SVG source.
  final String svg;
}
`;
}

export function swift(icons) {
  const cases = icons.map(({ name }) => `    case ${camelCase(name)} = "${name}"`).join('\n');
  return `// SPDX-License-Identifier: MPL-2.0
// ${HEADER}

import SwiftUI

/// UI icon set of project_alpha, backed by PaIcons.xcassets (vector, template rendering).
/// Tint with \`.foregroundStyle(...)\`; size with \`.resizable().frame(...)\` or \`.font\`-relative frames.
public enum PaIcon: String, CaseIterable, Sendable {
${cases}

    /// Asset name in PaIcons.xcassets.
    public var assetName: String { "pa." + rawValue }

    /// Template image; pass \`bundle\` when the catalog lives in a Swift package.
    public func image(bundle: Bundle? = nil) -> Image {
        Image(assetName, bundle: bundle).renderingMode(.template)
    }
}
`;
}

const json = (o) => JSON.stringify(o, null, 2) + '\n';

/** Map of absolute path -> content for everything we generate. */
export async function generate() {
  const manifest = await loadManifest();
  const names = Object.keys(manifest.icons).sort();
  const icons = await Promise.all(
    names.map(async (name) => ({ name, svg: await readFile(path.join(SVG_DIR, `${name}.svg`), 'utf8') })),
  );
  const out = new Map();
  out.set(DART_FILE, dart(icons));
  out.set(path.join(APPLE_DIR, 'PaIcon.swift'), swift(icons));
  const cat = path.join(APPLE_DIR, 'PaIcons.xcassets');
  out.set(path.join(cat, 'Contents.json'), json({ info: { author: 'xcode', version: 1 } }));
  for (const { name, svg } of icons) {
    const set = path.join(cat, `pa.${name}.imageset`);
    out.set(path.join(set, `${name}.svg`), svg);
    out.set(
      path.join(set, 'Contents.json'),
      json({
        images: [{ filename: `${name}.svg`, idiom: 'universal' }],
        info: { author: 'xcode', version: 1 },
        properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
      }),
    );
  }
  return out;
}

async function listFiles(dir) {
  const res = [];
  try {
    for (const e of await readdir(dir, { withFileTypes: true, recursive: true })) {
      if (e.isFile()) res.push(path.join(e.parentPath ?? e.path, e.name));
    }
  } catch (e) {
    if (e.code !== 'ENOENT') throw e;
  }
  return res;
}

async function main() {
  const check = process.argv.includes('--check');
  const out = await generate();
  const stale = [];
  for (const [file, content] of out) {
    const current = await readFile(file, 'utf8').catch(() => null);
    if (current === content) continue;
    if (check) stale.push(file);
    else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, content);
    }
  }
  for (const file of await listFiles(APPLE_DIR)) {
    if (out.has(file)) continue;
    if (check) stale.push(file);
    else await rm(file);
  }
  if (check) {
    if (stale.length) {
      console.error(stale.map((f) => `stale: ${path.relative(REPO_DIR, f)}`).join('\n'));
      console.error('\nicons:check failed: run `just design icons` and commit the result');
      process.exit(1);
    }
    console.log(`icons:check OK: ${out.size} generated files up to date`);
  } else {
    // Remove empty imagesets left from deleted icons.
    for (const e of await readdir(path.join(APPLE_DIR, 'PaIcons.xcassets'))) {
      const dir = path.join(APPLE_DIR, 'PaIcons.xcassets', e);
      if (e.endsWith('.imageset') && (await listFiles(dir)).length === 0) await rm(dir, { recursive: true });
    }
    console.log(`icons:build wrote ${out.size} files`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
