// Generates fonts/specimen.html — the ru/en type specimen for owner approval
// (DSN-005) — from the typography tokens of every density profile.
// Open it after `npm run fonts:fetch` (it loads fonts/files/InterVariable.woff2).

import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { flatten, resolve } from './lib/dtcg.mjs';
import { DESIGN_DIR } from './lib/icons.mjs';

const T = path.join(DESIGN_DIR, 'tokens');
const load = async (rel) => flatten(JSON.parse(await readFile(path.join(T, rel), 'utf8')), rel, []);

const SAMPLES = {
  display: ['Интерстеллар', 'Interstellar'],
  title1: ['Продолжить просмотр', 'Continue Watching'],
  title2: ['Сериалы · Сезон 2', 'TV Shows · Season 2'],
  headline: ['Недавно добавленные', 'Recently Added'],
  subtitle: ['Режиссёр — Кристофер Нолан', 'Directed by Christopher Nolan'],
  body: [
    'Съешь же ещё этих мягких французских булок, да выпей чаю. Когда Земля становится непригодной для жизни, группа исследователей отправляется сквозь червоточину.',
    'The quick brown fox jumps over the lazy dog. When Earth becomes uninhabitable, a team of explorers travels through a wormhole.',
  ],
  callout: ['Смотреть с 01:12:45', 'Resume from 01:12:45'],
  caption: ['2014 · 2 ч 49 мин · 16+ · 4K HDR', '2014 · 2 h 49 min · PG-13 · 4K HDR'],
  caption2: ['4K · HDR10 · 5.1 · 24,6 Мбит/с', '4K · HDR10 · 5.1 · 24.6 Mbit/s'],
  timecode: ['01:12:45 / 02:49:03', '01:12:45 / 02:49:03'],
};

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

async function main() {
  const base = new Map([...(await load('primitive.tokens.json')), ...(await load('semantic.tokens.json'))]);
  const sections = [];
  for (const f of (await readdir(path.join(T, 'density'))).sort()) {
    const name = f.replace('.tokens.json', '');
    const all = new Map([...base, ...(await load(`density/${f}`))]);
    const rows = Object.entries(SAMPLES).map(([style, [ru, en]]) => {
      const t = resolve(all, `type.${style}`);
      const size = t.fontSize.value;
      const tnum = ['caption2', 'timecode'].includes(style);
      const css = [
        `font-size:${size}px`,
        `line-height:${t.lineHeight}`,
        `font-weight:${t.fontWeight}`,
        `letter-spacing:${t.letterSpacing.value}px`,
        `font-variation-settings:'opsz' ${Math.min(32, Math.max(14, size))}`,
        tnum ? "font-feature-settings:'tnum'" : '',
      ].filter(Boolean).join(';');
      const meta = `${style} · ${size}/${Math.round(size * t.lineHeight)} · ${t.fontWeight}${tnum ? ' · tnum' : ''}`;
      return `<tr><th>${meta}</th><td lang="ru" style="${css}">${esc(ru)}</td><td lang="en" style="${css}">${esc(en)}</td></tr>`;
    });
    sections.push(`<section><h2>${name}</h2><table>${rows.join('\n')}</table></section>`);
  }
  const html = `<!doctype html>
<!-- SPDX-License-Identifier: MPL-2.0 -->
<!-- GENERATED by design/scripts/fonts-specimen.mjs from design/tokens. Do not edit. -->
<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Inter type specimen</title>
<style>
@font-face{font-family:Inter;font-style:normal;font-weight:100 900;src:url(files/InterVariable.woff2) format('woff2')}
:root{color-scheme:dark;--bg:#0b0b0f;--fg:#fff;--fg2:rgba(255,255,255,.64);--line:rgba(255,255,255,.12)}
body{margin:0;padding:32px;background:var(--bg);color:var(--fg);font-family:Inter,system-ui,sans-serif}
h1{font-size:28px;margin:0 0 4px}p.note{color:var(--fg2);margin:0 0 32px;max-width:900px}
h2{font-size:15px;text-transform:uppercase;letter-spacing:.08em;color:var(--fg2);border-top:1px solid var(--line);padding-top:16px}
table{border-collapse:collapse;width:100%}th{font:500 11px/1.3 Inter,sans-serif;color:var(--fg2);text-align:left;vertical-align:top;padding:12px 16px 12px 0;width:180px;font-feature-settings:'tnum'}
td{padding:8px 24px 8px 0;vertical-align:top;width:45%}
</style></head><body>
<h1>Inter Variable 4.1 — образец типографики (ru / en)</h1>
<p class="note">Сгенерировано из <code>design/tokens/density/*.tokens.json</code>. Если текст выглядит системным шрифтом — сначала выполните <code>just design fonts</code>. Размеры в px = pt; TV — холст 1920×1080, смотреть на телевизоре или с расстояния. На Apple-платформах используется системный SF, а не Inter.</p>
${sections.join('\n')}
</body></html>
`;
  await writeFile(path.join(DESIGN_DIR, 'fonts', 'specimen.html'), html);
  console.log('wrote fonts/specimen.html');
}

main();
